import fs from 'node:fs';
import assert from 'node:assert/strict';
const read=p=>fs.readFileSync(p,'utf8');
const memory=read('apps/api/src/business-memory.ts');
const memoryRoute=read('apps/api/src/routes-business-memory.ts');
const backup=read('apps/api/src/routes-backup-security.ts');
const migration=read('infra/postgres/037_knowledge_security_backup.sql');
const ui=read('apps/web/src/KnowledgeSecurityCenter.tsx');
const brief=read('apps/api/src/business-change-digest.ts');
const main=read('apps/web/src/main.tsx');
const agent=read('tools/nexoffice-backup-agent.mjs');

assert.ok(memoryRoute.includes("app.post('/v1/intelligence/ask'"),'ask route missing');
assert.ok(memory.includes("hasPermission(ctx.role,ctx.permissions,'crm.read')"),'CRM permission scope missing');
assert.ok(memory.includes("hasPermission(ctx.role,ctx.permissions,'finance.read')"),'finance permission scope missing');
assert.ok(memory.includes("hasPermission(ctx.role,ctx.permissions,'agenda.read')"),'agenda permission scope missing');
assert.ok(memory.includes("hasPermission(ctx.role,ctx.permissions,'documents.read')"),'document permission scope missing');
for(const invariant of ['rawDocumentsUsed:false','rawDocumentTextStored:false','docWalletStructuredIntelligenceOnly:true','externalLLMUsed:false','embeddingsUsed:false','generativeCompletionUsed:false','externalEffect:false'])assert.ok(memory.includes(invariant),`memory invariant missing ${invariant}`);
assert.ok(!memory.includes('OPENAI_API_KEY')&&!memory.includes('ANTHROPIC_API_KEY'),'business memory must not require external LLM');
assert.ok(migration.includes('token_hash text not null unique'),'backup agent token must be hashed');
assert.ok(migration.includes('customer_owned'),'backup must use customer-owned target model');
for(const forbidden of ['repository_url','repository_password','access_key','secret_key','backup_content','file_content'])assert.ok(!migration.includes(forbidden),`forbidden secret/content column ${forbidden}`);
assert.ok(backup.includes("repositoryCredentialsStoredInNexOffice:false"),'repository credential boundary missing');
assert.ok(backup.includes("resticPasswordStoredInNexOffice:false"),'Restic password boundary missing');
assert.ok(backup.includes("backupBytesStoredInNexOffice:false"),'backup byte boundary missing');
assert.ok(backup.includes("remoteExecution:false"),'remote execution must remain off');
assert.ok(agent.includes("RESTIC_REPOSITORY=<configure somente localmente>")===false,'agent script must not contain fake repository setup text');
assert.ok(agent.includes("process.env.RESTIC_BIN||'restic'"),'agent must call local Restic binary');
assert.ok(agent.includes("'x-backup-agent-token':TOKEN"),'agent reporting auth missing');
assert.ok(!agent.includes('RESTIC_PASSWORD_FILE:')&&!agent.includes('RESTIC_REPOSITORY:'),'agent must not post Restic secrets');
assert.ok(brief.includes('rawDocumentsIncluded:false')&&brief.includes('backupContentsIncluded:false'),'change digest privacy boundary missing');
assert.ok(ui.includes('Pergunte à empresa')&&ui.includes('Backup empresarial'),'combined Knowledge & Security UX missing');
assert.ok(ui.includes('Sem LLM externo')&&ui.includes('Sem texto bruto de documentos'),'memory transparency copy missing');
assert.ok(ui.includes('Sem execução remota'),'backup execution boundary copy missing');
assert.ok(main.includes('<KnowledgeSecurityCenter/>'),'Knowledge & Security workspace not mounted');
console.log(JSON.stringify({ok:true,module:'Knowledge & Security V1',structuredMemory:true,externalLLM:false,rawDocuments:false,customerOwnedBackup:true,remoteExecution:false,whatChanged:true}));
